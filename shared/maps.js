// Описание карт в стиле контр-страйка: длинные линии, арки, лестницы, ящики, бочки.
// Координаты: x ∈ [-48,48], z ∈ [-60,60]. Атакующие (команда 0) стартуют на юге (z>0), защитники — на севере.
export const SIZE = { x: 48, z: 60 };

export function makeApi(out) {
  const R = (x0, z0, x1, z1, h = 6, kind = 'wall', y0 = 0) => { out.push({ x0: Math.min(x0, x1), x1: Math.max(x0, x1), z0: Math.min(z0, z1), z1: Math.max(z0, z1), y0, y1: h, kind }); };
  const A = {
    R,
    /** стена вдоль X на высоте z, от xa до xb */
    wallH: (z, xa, xb, h = 6, kind = 'wall', t = 2) => R(xa, z - t / 2, xb, z + t / 2, h, kind),
    /** стена вдоль Z на x, от za до zb */
    wallV: (x, za, zb, h = 6, kind = 'wall', t = 2) => R(x - t / 2, za, x + t / 2, zb, h, kind),
    /** перемычка над проёмом (арка): не мешает проходу, перекрывает обзор сверху */
    arch: (x0, z0, x1, z1, y0 = 3.2, y1 = 6) => R(x0, z0, x1, z1, y1, 'wall', y0),
    crate: (x, z, s = 2, h = s) => R(x - s / 2, z - s / 2, x + s / 2, z + s / 2, h, 'crate'),
    barrel: (x, z) => R(x - 0.5, z - 0.5, x + 0.5, z + 0.5, 1.15, 'barrel'),
    dump: (x0, z0, x1, z1) => R(x0, z0, x1, z1, 1.6, 'dumpster'),
    low: (x0, z0, x1, z1, h = 1.2) => R(x0, z0, x1, z1, h, 'low'),
    sand: (x0, z0, x1, z1) => R(x0, z0, x1, z1, 1.0, 'sand'),
    /** лестница: ступени по оси 'x' или 'z', направление подъёма dir=+1/-1, n ступеней до высоты top */
    stairs(x0, z0, x1, z1, axis, dir, n, top) {
      for (let i = 0; i < n; i++) {
        const h = top * (i + 1) / n;
        if (axis === 'z') {
          const len = (Math.max(z0, z1) - Math.min(z0, z1)) / n, a = Math.min(z0, z1);
          const s = dir > 0 ? a + len * i : a + len * (n - 1 - i);
          R(x0, s, x1, s + len, h, 'step');
        } else {
          const len = (Math.max(x0, x1) - Math.min(x0, x1)) / n, a = Math.min(x0, x1);
          const s = dir > 0 ? a + len * i : a + len * (n - 1 - i);
          R(s, z0, s + len, z1, h, 'step');
        }
      }
    },
    perimeter(h = 9) {
      R(-SIZE.x - 1, -SIZE.z - 1, -SIZE.x, SIZE.z + 1, h); R(SIZE.x, -SIZE.z - 1, SIZE.x + 1, SIZE.z + 1, h);
      R(-SIZE.x, SIZE.z, SIZE.x, SIZE.z + 1, h); R(-SIZE.x, -SIZE.z - 1, SIZE.x, -SIZE.z, h);
    },
  };
  return A;
}

